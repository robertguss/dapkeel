pub fn connect_pg(conn_str: &str) -> Result<Client, DapError> {
    let parsed = Url::parse(conn_str).map_err(|e| {
        DapError::config(
            format!("Invalid PostgreSQL connection string: {e}"),
            "Provide a valid RFC 3986 URL via --connection-string, DAP_CONNECTION_STRING, or DATABASE_URL.",
        )
    })?;

    let sslmode = parsed
        .query_pairs()
        .find(|(k, _)| k.eq_ignore_ascii_case("sslmode"))
        .map(|(_, v)| v.to_ascii_lowercase())
        .unwrap_or_else(|| "prefer".to_string());

    let redacted = redact_url_password(conn_str);

    if sslmode == "disable" {
        return Client::connect(conn_str, NoTls).map_err(|e| {
            DapError::db(
                format!("Failed to connect to PostgreSQL ({redacted}): {e}"),
                Some("Verify host, port, credentials, and network reachability.".to_string()),
            )
        });
    }

    let connector = TlsConnector::builder()
        .danger_accept_invalid_certs(sslmode == "prefer" || sslmode == "allow")
        .build()
        .map_err(|e| DapError::db(format!("TLS initialization error: {e}"), None))?;
    let tls = MakeTlsConnector::new(connector);

    match Client::connect(conn_str, tls) {
        Ok(c) => Ok(c),
        Err(tls_err) if sslmode == "prefer" || sslmode == "allow" => Client::connect(
            conn_str, NoTls,
        )
        .map_err(|plain_err| {
            DapError::db(
                format!(
                    "Failed to connect to PostgreSQL ({redacted}): TLS={tls_err}; NoTls={plain_err}"
                ),
                Some("Check server status or set ?sslmode=disable / ?sslmode=require.".to_string()),
            )
        }),
        Err(e) => Err(DapError::db(
            format!("Failed to connect to PostgreSQL ({redacted}): {e}"),
            Some("Verify TLS certificates and database credentials.".to_string()),
        )),
    }
}

pub fn ensure_meta_table(client: &mut Client, meta_schema: &str) -> Result<(), DapError> {
    let q_schema = quote_ident(meta_schema);
    client
        .batch_execute(&format!(
            "CREATE SCHEMA IF NOT EXISTS {q_schema};
             CREATE TABLE IF NOT EXISTS {q_schema}.table_sync (
                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 source_namespace VARCHAR(64) NOT NULL,
                 source_table VARCHAR(64) NOT NULL,
                 timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                 schema_version INTEGER NOT NULL,
                 target_schema VARCHAR(64),
                 target_table VARCHAR(64) NOT NULL,
                 schema_description_format VARCHAR(64) NOT NULL,
                 schema_description TEXT NOT NULL,
                 UNIQUE (source_namespace, source_table)
             );"
        ))
        .map_err(|e| {
            DapError::db(
                format!("Failed ensuring {meta_schema}.table_sync: {e}"),
                None,
            )
        })
}

pub fn get_table_sync_meta(
    client: &mut Client,
    meta_schema: &str,
    namespace: &str,
    table: &str,
) -> Result<Option<TableSyncMeta>, DapError> {
    let q_schema = quote_ident(meta_schema);
    let row = client
        .query_opt(
            &format!(
                "SELECT id, source_namespace, source_table, timestamp, schema_version,
                        COALESCE(target_schema, source_namespace), target_table,
                        schema_description_format, schema_description
                 FROM {q_schema}.table_sync
                 WHERE source_namespace = $1 AND source_table = $2"
            ),
            &[&namespace, &table],
        )
        .map_err(|e| DapError::db(format!("Failed reading table_sync metadata: {e}"), None))?;

    Ok(row.map(|r| {
        let ts: NaiveDateTime = r.get(3);
        TableSyncMeta {
            id: r.get(0),
            source_namespace: r.get(1),
            source_table: r.get(2),
            timestamp: DateTime::<Utc>::from_naive_utc_and_offset(ts, Utc),
            schema_version: r.get(4),
            target_schema: r.get(5),
            target_table: r.get(6),
            schema_description_format: r.get(7),
            schema_description: r.get(8),
        }
    }))
}

/// Bulk-load initial snapshot files into PostgreSQL inside a single atomic transaction.
#[allow(clippy::too_many_arguments)]
pub fn initdb_apply(
    conn_str: &str,
    meta_schema: &str,
    target_schema: &str,
    spec: &TableSpec,
    schema_json: &str,
    watermark: DateTime<Utc>,
    files: &[PathBuf],
    dry_run: bool,
) -> Result<InitDbTableReport, DapError> {
    let ddl = create_table_ddl(target_schema, &spec.table, spec);
    if dry_run {
        return Ok(InitDbTableReport {
            namespace: spec.namespace.clone(),
            table: spec.table.clone(),
            target: format!("{}.{}", target_schema, spec.table),
            schema_version: spec.schema_version,
            timestamp: watermark,
            rows_loaded: 0,
            duplicates_deduped: 0,
            dry_run: true,
            ddl: Some(ddl),
        });
    }

    let mut client = connect_pg(conn_str)?;
    ensure_meta_table(&mut client, meta_schema)?;

    if get_table_sync_meta(&mut client, meta_schema, &spec.namespace, &spec.table)?.is_some() {
        return Err(DapError::already_initialized(&spec.namespace, &spec.table));
    }

    // Parse & deduplicate rows by primary key (last-wins), handling tables like canvas_logs.web_logs
    let mut deduped: IndexMap<String, Map<String, Value>> = IndexMap::new();
    let mut raw_rows = Vec::new();
    let mut duplicates = 0u64;

    for path in files {
        let mut reader = open_maybe_gzip(path)?;
        let mut line = String::new();
        loop {
            line.clear();
            let n = reader
                .read_line(&mut line)
                .map_err(|e| DapError::io(format!("Failed reading '{}': {e}", path.display())))?;
            if n == 0 {
                break;
            }
            let trimmed = line.trim();
            if trimmed.is_empty() {
                continue;
            }
            let rec = unpack_dap_json_line(trimmed, false)?;
            if spec.primary_keys.is_empty() {
                raw_rows.push(rec.flat);
            } else {
                let pk_key = composite_pk_key(&rec.flat, &spec.primary_keys);
                if deduped.insert(pk_key, rec.flat).is_some() {
                    duplicates += 1;
                }
            }
        }
    }

    let rows: Vec<Map<String, Value>> = if spec.primary_keys.is_empty() {
        raw_rows
    } else {
        deduped.into_values().collect()
    };

    let mut tx = client
        .transaction()
        .map_err(|e| DapError::db(format!("Failed starting Postgres transaction: {e}"), None))?;

    let q_target_schema = quote_ident(target_schema);
    let q_meta_schema = quote_ident(meta_schema);

    tx.batch_execute(&format!(
        "CREATE SCHEMA IF NOT EXISTS {q_target_schema};\n{ddl}"
    ))
    .map_err(|e| DapError::db(format!("Failed creating target table: {e}"), None))?;

    let rows_loaded = rows.len() as u64;
    if !rows.is_empty() {
        stage_and_upsert(
            &mut tx,
            target_schema,
            &spec.table,
            &spec.columns,
            &spec.primary_keys,
            &rows,
            false,
        )?;
    }

    let naive_ts = watermark.naive_utc();
    tx.execute(
        &format!(
            "INSERT INTO {q_meta_schema}.table_sync
             (source_namespace, source_table, timestamp, schema_version, target_schema, target_table, schema_description_format, schema_description)
             VALUES ($1, $2, $3, $4, $5, $6, 'json', $7)"
        ),
        &[
            &spec.namespace,
            &spec.table,
            &naive_ts,
            &spec.schema_version,
            &target_schema,
            &spec.table,
            &schema_json,
        ],
    )
    .map_err(|e| DapError::db(format!("Failed inserting table_sync metadata: {e}"), None))?;

    tx.commit()
        .map_err(|e| DapError::db(format!("Failed committing initdb transaction: {e}"), None))?;

    Ok(InitDbTableReport {
        namespace: spec.namespace.clone(),
        table: spec.table.clone(),
        target: format!("{}.{}", target_schema, spec.table),
        schema_version: spec.schema_version,
        timestamp: watermark,
        rows_loaded,
        duplicates_deduped: duplicates,
        dry_run: false,
        ddl: None,
    })
}

/// Apply incremental CDC files ("U" upserts and "D" deletes) + schema evolution inside ONE atomic transaction.
#[allow(clippy::too_many_arguments)]
pub fn syncdb_apply(
    conn_str: &str,
    meta_schema: &str,
    meta: &TableSyncMeta,
    spec: &TableSpec,
    schema_json: &str,
    new_watermark: DateTime<Utc>,
    files: &[PathBuf],
    soft_delete: bool,
    dry_run: bool,
) -> Result<SyncDbTableReport, DapError> {
    // Collapse CDC events per primary key in stream order: latest event wins (U vs D)
    enum CdcEvent {
        Upsert(Map<String, Value>),
        Delete(Map<String, Value>),
    }

    let mut per_pk: IndexMap<String, CdcEvent> = IndexMap::new();
    let mut unkeyed_upserts: Vec<Map<String, Value>> = Vec::new();

    for path in files {
        let mut reader = open_maybe_gzip(path)?;
        let mut line = String::new();
        loop {
            line.clear();
            let n = reader
                .read_line(&mut line)
                .map_err(|e| DapError::io(format!("Failed reading '{}': {e}", path.display())))?;
            if n == 0 {
                break;
            }
            let trimmed = line.trim();
            if trimmed.is_empty() {
                continue;
            }
            let rec = unpack_dap_json_line(trimmed, false)?;
            let is_delete = rec
                .action
                .as_deref()
                .map(|a| a.eq_ignore_ascii_case("D"))
                .unwrap_or(false);

            if spec.primary_keys.is_empty() {
                if !is_delete {
                    unkeyed_upserts.push(rec.flat);
                }
            } else {
                let pk_key = composite_pk_key(&rec.flat, &spec.primary_keys);
                if is_delete {
                    per_pk.insert(pk_key, CdcEvent::Delete(rec.flat));
                } else {
                    per_pk.insert(pk_key, CdcEvent::Upsert(rec.flat));
                }
            }
        }
    }

    let mut upserts = unkeyed_upserts;
    let mut deletes = Vec::new();
    for event in per_pk.into_values() {
        match event {
            CdcEvent::Upsert(row) => upserts.push(row),
            CdcEvent::Delete(row) => deletes.push(row),
        }
    }

    if dry_run {
        return Ok(SyncDbTableReport {
            namespace: spec.namespace.clone(),
            table: spec.table.clone(),
            target: format!("{}.{}", meta.target_schema, meta.target_table),
            previous_timestamp: meta.timestamp,
            new_timestamp: new_watermark,
            schema_version: spec.schema_version,
            columns_added: Vec::new(),
            rows_upserted: upserts.len() as u64,
            rows_deleted: deletes.len() as u64,
            soft_delete,
            dry_run: true,
        });
    }

    let mut client = connect_pg(conn_str)?;
    ensure_meta_table(&mut client, meta_schema)?;

    let mut tx = client
        .transaction()
        .map_err(|e| DapError::db(format!("Failed starting syncdb transaction: {e}"), None))?;

    // Auto-evolve newly added columns from DAP schema evolution
    let existing_cols = fetch_existing_columns(&mut tx, &meta.target_schema, &meta.target_table)?;
    let mut columns_added = Vec::new();
    let q_target = format!(
        "{}.{}",
        quote_ident(&meta.target_schema),
        quote_ident(&meta.target_table)
    );

    for col in &spec.columns {
        if !existing_cols.contains(&col.name) {
            tx.batch_execute(&format!(
                "ALTER TABLE {q_target} ADD COLUMN IF NOT EXISTS {} {};",
                quote_ident(&col.name),
                col.pg_type
            ))
            .map_err(|e| {
                DapError::db(
                    format!("Failed evolving column '{}' on {q_target}: {e}", col.name),
                    None,
                )
            })?;
            columns_added.push(col.name.clone());
        }
    }

    if soft_delete && !existing_cols.contains("_dap_deleted") {
        tx.batch_execute(&format!(
            "ALTER TABLE {q_target} ADD COLUMN IF NOT EXISTS \"_dap_deleted\" BOOLEAN NOT NULL DEFAULT FALSE;"
        ))
        .map_err(|e| {
            DapError::db(
                format!("Failed adding _dap_deleted column on {q_target}: {e}"),
                None,
            )
        })?;
        columns_added.push("_dap_deleted".to_string());
    }

    if !upserts.is_empty() {
        stage_and_upsert(
            &mut tx,
            &meta.target_schema,
            &meta.target_table,
            &spec.columns,
            &spec.primary_keys,
            &upserts,
            soft_delete,
        )?;
    }

    if !deletes.is_empty() && !spec.primary_keys.is_empty() {
        apply_deletes(
            &mut tx,
            &meta.target_schema,
            &meta.target_table,
            &spec.columns,
            &spec.primary_keys,
            &deletes,
            soft_delete,
        )?;
    }

    let q_meta_schema = quote_ident(meta_schema);
    let naive_ts = new_watermark.naive_utc();
    tx.execute(
        &format!(
            "UPDATE {q_meta_schema}.table_sync
             SET timestamp = $1, schema_version = $2, schema_description = $3
             WHERE id = $4"
        ),
        &[&naive_ts, &spec.schema_version, &schema_json, &meta.id],
    )
    .map_err(|e| DapError::db(format!("Failed updating table_sync metadata: {e}"), None))?;

    tx.commit()
        .map_err(|e| DapError::db(format!("Failed committing syncdb transaction: {e}"), None))?;

    Ok(SyncDbTableReport {
        namespace: spec.namespace.clone(),
        table: spec.table.clone(),
        target: format!("{}.{}", meta.target_schema, meta.target_table),
        previous_timestamp: meta.timestamp,
        new_timestamp: new_watermark,
        schema_version: spec.schema_version,
        columns_added,
        rows_upserted: upserts.len() as u64,
        rows_deleted: deletes.len() as u64,
        soft_delete,
        dry_run: false,
    })
}

pub fn listdb(
    conn_str: &str,
    meta_schema: &str,
    namespace: &str,
    remote_tables: Option<&[String]>,
    omit_record_count: bool,
    omit_not_replicated: bool,
) -> Result<Vec<ListDbEntry>, DapError> {
    let mut client = connect_pg(conn_str)?;
    ensure_meta_table(&mut client, meta_schema)?;

    let q_meta = quote_ident(meta_schema);
    let rows = client
        .query(
            &format!(
                "SELECT id, source_namespace, source_table, timestamp, schema_version,
                        COALESCE(target_schema, source_namespace), target_table,
                        schema_description_format, schema_description
                 FROM {q_meta}.table_sync
                 WHERE source_namespace = $1
                 ORDER BY source_table"
            ),
            &[&namespace],
        )
        .map_err(|e| DapError::db(format!("Failed querying table_sync: {e}"), None))?;

    let mut metas: IndexMap<String, TableSyncMeta> = IndexMap::new();
    for r in rows {
        let ts: NaiveDateTime = r.get(3);
        let m = TableSyncMeta {
            id: r.get(0),
            source_namespace: r.get(1),
            source_table: r.get(2),
            timestamp: DateTime::<Utc>::from_naive_utc_and_offset(ts, Utc),
            schema_version: r.get(4),
            target_schema: r.get(5),
            target_table: r.get(6),
            schema_description_format: r.get(7),
            schema_description: r.get(8),
        };
        metas.insert(m.source_table.clone(), m);
    }

    let mut all_names: Vec<String> = metas.keys().cloned().collect();
    if !omit_not_replicated && let Some(remote) = remote_tables {
        for name in remote {
            if !metas.contains_key(name) {
                all_names.push(name.clone());
            }
        }
    }
    all_names.sort();
    all_names.dedup();

    let now = Utc::now();
    let mut entries = Vec::with_capacity(all_names.len());
    for name in all_names {
        if let Some(meta) = metas.get(&name) {
            let count = if omit_record_count {
                None
            } else {
                let q_from = format!(
                    "{}.{}",
                    quote_ident(&meta.target_schema),
                    quote_ident(&meta.target_table)
                );
                let c: i64 = client
                    .query_one(&format!("SELECT COUNT(*) FROM {q_from}"), &[])
                    .map(|r| r.get(0))
                    .unwrap_or(0);
                Some(c)
            };
            entries.push(ListDbEntry {
                name,
                records: count,
                timestamp: Some(meta.timestamp),
                staleness: Some(format_staleness(now - meta.timestamp)),
                schema_version: Some(meta.schema_version),
                command: "syncdb".to_string(),
            });
        } else {
            entries.push(ListDbEntry {
                name,
                records: None,
                timestamp: None,
                staleness: None,
                schema_version: None,
                command: "initdb".to_string(),
            });
        }
    }

    Ok(entries)
}

pub fn dropdb_tables(
    conn_str: &str,
    meta_schema: &str,
    namespace: &str,
    tables_arg: &str,
) -> Result<Vec<DropDbTableReport>, DapError> {
    let mut client = connect_pg(conn_str)?;
    ensure_meta_table(&mut client, meta_schema)?;

    let q_meta = quote_ident(meta_schema);
    let target_names: Vec<String> = if tables_arg.trim().eq_ignore_ascii_case("all") {
        let rows = client
            .query(
                &format!(
                    "SELECT source_table FROM {q_meta}.table_sync WHERE source_namespace = $1 ORDER BY source_table"
                ),
                &[&namespace],
            )
            .map_err(|e| DapError::db(format!("Failed querying table_sync: {e}"), None))?;
        rows.into_iter().map(|r| r.get(0)).collect()
    } else {
        tables_arg
            .split(',')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect()
    };

    let mut reports = Vec::new();
    for tbl in target_names {
        let meta = get_table_sync_meta(&mut client, meta_schema, namespace, &tbl)?;
        let Some(meta) = meta else {
            reports.push(DropDbTableReport {
                namespace: namespace.to_string(),
                table: tbl.clone(),
                target: format!("{namespace}.{tbl}"),
                dropped: false,
            });
            continue;
        };

        let mut tx = client
            .transaction()
            .map_err(|e| DapError::db(format!("Failed starting dropdb transaction: {e}"), None))?;

        let q_target = format!(
            "{}.{}",
            quote_ident(&meta.target_schema),
            quote_ident(&meta.target_table)
        );
        tx.batch_execute(&format!("DROP TABLE IF EXISTS {q_target};"))
            .map_err(|e| DapError::db(format!("Failed dropping table {q_target}: {e}"), None))?;

        tx.execute(
            &format!("DELETE FROM {q_meta}.table_sync WHERE id = $1"),
            &[&meta.id],
        )
        .map_err(|e| DapError::db(format!("Failed removing table_sync row: {e}"), None))?;

        tx.commit().map_err(|e| {
            DapError::db(format!("Failed committing dropdb transaction: {e}"), None)
        })?;

        reports.push(DropDbTableReport {
            namespace: namespace.to_string(),
            table: tbl,
            target: format!("{}.{}", meta.target_schema, meta.target_table),
            dropped: true,
        });
    }

    Ok(reports)
}

fn fetch_existing_columns(
    tx: &mut postgres::Transaction<'_>,
    schema: &str,
    table: &str,
) -> Result<HashSet<String>, DapError> {
    let rows = tx
        .query(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = $1 AND table_name = $2",
            &[&schema, &table],
        )
        .map_err(|e| DapError::db(format!("Failed inspecting target columns: {e}"), None))?;
    Ok(rows.into_iter().map(|r| r.get(0)).collect())
}

fn stage_and_upsert(
    tx: &mut postgres::Transaction<'_>,
    target_schema: &str,
    target_table: &str,
    columns: &[ColumnSpec],
    primary_keys: &[String],
    rows: &[Map<String, Value>],
    reset_soft_delete: bool,
) -> Result<(), DapError> {
    let stage_name = "_dapkeel_stage";
    let q_target = format!(
        "{}.{}",
        quote_ident(target_schema),
        quote_ident(target_table)
    );

    let col_defs: Vec<String> = columns
        .iter()
        .map(|c| format!("{} {}", quote_ident(&c.name), c.pg_type))
        .collect();

    tx.batch_execute(&format!(
        "CREATE TEMP TABLE {stage_name} ({}) ON COMMIT DROP;",
        col_defs.join(", ")
    ))
    .map_err(|e| DapError::db(format!("Failed creating COPY staging table: {e}"), None))?;

    let col_list: Vec<String> = columns.iter().map(|c| quote_ident(&c.name)).collect();
    let copy_sql = format!("COPY {stage_name} ({}) FROM STDIN", col_list.join(", "));

    {
        let mut writer = tx
            .copy_in(&copy_sql)
            .map_err(|e| DapError::db(format!("Failed starting COPY FROM STDIN: {e}"), None))?;

        let mut buf = String::with_capacity(8192);
        for row in rows {
            buf.clear();
            for (idx, col) in columns.iter().enumerate() {
                if idx > 0 {
                    buf.push('\t');
                }
                match row.get(&col.name) {
                    None | Some(Value::Null) => buf.push_str("\\N"),
                    Some(v) => format_pg_copy_value(v, &col.pg_type, &mut buf),
                }
            }
            buf.push('\n');
            writer.write_all(buf.as_bytes()).map_err(|e| {
                DapError::db(
                    format!("Failed streaming COPY batch to Postgres: {e}"),
                    None,
                )
            })?;
        }
        writer
            .finish()
            .map_err(|e| DapError::db(format!("Failed finishing COPY FROM STDIN: {e}"), None))?;
    }

    let cols_joined = col_list.join(", ");
    if primary_keys.is_empty() {
        tx.batch_execute(&format!(
            "INSERT INTO {q_target} ({cols_joined}) SELECT {cols_joined} FROM {stage_name};"
        ))
        .map_err(|e| DapError::db(format!("Failed inserting staged rows: {e}"), None))?;
    } else {
        let pk_set: HashSet<&str> = primary_keys.iter().map(|s| s.as_str()).collect();
        let pk_joined = primary_keys
            .iter()
            .map(|k| quote_ident(k))
            .collect::<Vec<_>>()
            .join(", ");

        let mut set_clauses: Vec<String> = columns
            .iter()
            .filter(|c| !pk_set.contains(c.name.as_str()))
            .map(|c| {
                let q = quote_ident(&c.name);
                format!("{q} = EXCLUDED.{q}")
            })
            .collect();

        if reset_soft_delete {
            set_clauses.push("\"_dap_deleted\" = FALSE".to_string());
        }

        let conflict_clause = if set_clauses.is_empty() {
            format!("ON CONFLICT ({pk_joined}) DO NOTHING")
        } else {
            format!(
                "ON CONFLICT ({pk_joined}) DO UPDATE SET {}",
                set_clauses.join(", ")
            )
        };

        let insert_cols = if reset_soft_delete {
            format!("{cols_joined}, \"_dap_deleted\"")
        } else {
            cols_joined.clone()
        };
        let select_cols = if reset_soft_delete {
            format!("{cols_joined}, FALSE")
        } else {
            cols_joined
        };

        tx.batch_execute(&format!(
            "INSERT INTO {q_target} ({insert_cols})
             SELECT {select_cols} FROM {stage_name}
             {conflict_clause};"
        ))
        .map_err(|e| {
            DapError::db(
                format!("Failed upserting staged rows into {q_target}: {e}"),
                None,
            )
        })?;
    }

    tx.batch_execute(&format!("DROP TABLE IF EXISTS {stage_name};"))
        .map_err(|e| DapError::db(format!("Failed dropping temp stage table: {e}"), None))?;
    Ok(())
}

fn apply_deletes(
    tx: &mut postgres::Transaction<'_>,
    target_schema: &str,
    target_table: &str,
    columns: &[ColumnSpec],
    primary_keys: &[String],
    deletes: &[Map<String, Value>],
    soft_delete: bool,
) -> Result<(), DapError> {
    let del_stage = "_dapkeel_del";
    let q_target = format!(
        "{}.{}",
        quote_ident(target_schema),
        quote_ident(target_table)
    );

    let pk_specs: Vec<&ColumnSpec> = primary_keys
        .iter()
        .filter_map(|pk| columns.iter().find(|c| &c.name == pk))
        .collect();
    if pk_specs.is_empty() {
        return Ok(());
    }

    let col_defs: Vec<String> = pk_specs
        .iter()
        .map(|c| format!("{} {}", quote_ident(&c.name), c.pg_type))
        .collect();
    let col_list: Vec<String> = pk_specs.iter().map(|c| quote_ident(&c.name)).collect();

    tx.batch_execute(&format!(
        "CREATE TEMP TABLE {del_stage} ({}) ON COMMIT DROP;",
        col_defs.join(", ")
    ))
    .map_err(|e| DapError::db(format!("Failed creating delete staging table: {e}"), None))?;

    {
        let mut writer = tx
            .copy_in(&format!(
                "COPY {del_stage} ({}) FROM STDIN",
                col_list.join(", ")
            ))
            .map_err(|e| DapError::db(format!("Failed starting delete COPY: {e}"), None))?;
        let mut buf = String::with_capacity(4096);
        for row in deletes {
            buf.clear();
            for (idx, col) in pk_specs.iter().enumerate() {
                if idx > 0 {
                    buf.push('\t');
                }
                match row.get(&col.name) {
                    None | Some(Value::Null) => buf.push_str("\\N"),
                    Some(v) => format_pg_copy_value(v, &col.pg_type, &mut buf),
                }
            }
            buf.push('\n');
            writer
                .write_all(buf.as_bytes())
                .map_err(|e| DapError::db(format!("Failed streaming delete keys: {e}"), None))?;
        }
        writer
            .finish()
            .map_err(|e| DapError::db(format!("Failed finishing delete COPY: {e}"), None))?;
    }

    let join_cond = pk_specs
        .iter()
        .map(|c| {
            let q = quote_ident(&c.name);
            format!("t.{q} = d.{q}")
        })
        .collect::<Vec<_>>()
        .join(" AND ");

    if soft_delete {
        tx.batch_execute(&format!(
            "UPDATE {q_target} AS t SET \"_dap_deleted\" = TRUE FROM {del_stage} AS d WHERE {join_cond};"
        ))
        .map_err(|e| DapError::db(format!("Failed applying soft deletes on {q_target}: {e}"), None))?;
    } else {
        tx.batch_execute(&format!(
            "DELETE FROM {q_target} AS t USING {del_stage} AS d WHERE {join_cond};"
        ))
        .map_err(|e| DapError::db(format!("Failed applying deletes on {q_target}: {e}"), None))?;
    }

    tx.batch_execute(&format!("DROP TABLE IF EXISTS {del_stage};"))
        .map_err(|e| DapError::db(format!("Failed dropping temp delete table: {e}"), None))?;
    Ok(())
}

fn composite_pk_key(row: &Map<String, Value>, pks: &[String]) -> String {
    let mut out = String::new();
    for (i, pk) in pks.iter().enumerate() {
        if i > 0 {
            out.push('\u{001f}');
        }
        if let Some(v) = row.get(pk) {
            out.push_str(&v.to_string());
        }
    }
    out
}

fn format_pg_copy_value(val: &Value, pg_type: &str, out: &mut String) {
    let raw = if pg_type == "JSONB" {
        serde_json::to_string(val).unwrap_or_else(|_| "null".to_string())
    } else {
        match val {
            Value::String(s) => s.clone(),
            Value::Bool(b) => if *b { "t" } else { "f" }.to_string(),
            Value::Number(n) => n.to_string(),
            other => serde_json::to_string(other).unwrap_or_default(),
        }
    };
    for ch in raw.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\t' => out.push_str("\\t"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\0' => {}
            c => out.push(c),
        }
    }
}

fn format_staleness(delta: chrono::Duration) -> String {
    let secs = delta.num_seconds().max(0);
    if secs < 60 {
        format!("{secs}s ago")
    } else if secs < 3600 {
        format!("{}m ago", secs / 60)
    } else if secs < 86400 {
        format!("{}h {}m ago", secs / 3600, (secs % 3600) / 60)
    } else {
        format!("{}d {}h ago", secs / 86400, (secs % 86400) / 3600)
    }
}
